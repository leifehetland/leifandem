#!/usr/bin/env node
/**
 * One-shot regen of media-manifest.ts from the current filesystem.
 * Mirrors scripts/generate-manifest.mjs but uses ImageMagick `identify`
 * for dimensions instead of `webpinfo` (which isn't installed here).
 */

import { execFileSync } from 'node:child_process';
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, basename } from 'node:path';

const ROOT = '/sessions/determined-ecstatic-brown/mnt/leifandem';
const IMG_DIR = join(ROOT, 'public/media/images');
const OUT_FILE = join(ROOT, 'src/lib/media-manifest.ts');

const FOLDER_LABELS = {
  '.': 'A moment from us.',
  atlceremony: 'Our ceremony and reception.',
  polaroidscans: 'A polaroid we kept.',
  primaryphotos: 'One of our favorites.',
  throwbacks: 'A throwback.',
  our_parents: 'Our parents, before us.',
};

function* walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    const st = statSync(p);
    if (st.isDirectory()) yield* walk(p);
    else if (st.isFile() && p.toLowerCase().endsWith('.webp')) yield p;
  }
}

function readDims(file) {
  // `identify -format "%w %h" file[0]` outputs e.g. "1024 768"
  const out = execFileSync('identify', ['-format', '%w %h', `${file}[0]`], {
    encoding: 'utf8',
  }).trim();
  const [w, h] = out.split(/\s+/).map(Number);
  if (!w || !h) throw new Error(`No dims for ${file}: got "${out}"`);
  return { width: w, height: h };
}

const items = [];
const seenIds = new Set();
for (const file of walk(IMG_DIR)) {
  const rel = relative(IMG_DIR, file);
  const parts = rel.split('/');
  const folder = parts.length > 1 ? parts[0] : '.';
  const stem = basename(rel, '.webp');
  let id = folder === '.' ? stem : `${folder}-${stem}`;
  let n = 2;
  const base = id;
  while (seenIds.has(id)) id = `${base}-${n++}`;
  seenIds.add(id);
  const { width, height } = readDims(file);
  const caption = FOLDER_LABELS[folder] ?? FOLDER_LABELS['.'];
  const alt =
    folder === '.'
      ? `Photo: ${stem}`
      : `Photo from ${folder.replace(/_/g, ' ')}: ${stem}`;
  items.push({
    id,
    src: `/media/images/${rel}`,
    width,
    height,
    caption,
    alt,
  });
}

items.sort((a, b) => a.id.localeCompare(b.id));

const header = `/**
 * Canonical media manifest. The 3D scene and the 2D fallback both map over
 * this list — components do not hardcode \`/media/...\` paths.
 *
 * Generated by scripts/generate-manifest.mjs. To add/remove media:
 *   1. Drop a source image into src/imgs/ (any subfolder)
 *   2. Run \`bash scripts/convert-imgs.sh\`
 *   3. Run \`node scripts/generate-manifest.mjs\`
 *
 * \`position\` is optional. When omitted, Cards.tsx assigns one at runtime
 * (deterministic per page-load seed). Set it explicitly here to pin a card.
 */

export type MediaPosition = [x: number, y: number, z: number];
export type MediaRotation = [x: number, y: number, z: number];

interface BaseItem {
  id: string;
  caption: string;
  alt: string;
  position?: MediaPosition;
  rotation?: MediaRotation;
  scale?: number;
  tier?: 'all' | 'mid+' | 'high';
}

export interface PhotoItem extends BaseItem {
  type: 'photo';
  src: string;
  width: number;
  height: number;
}

export interface VideoItem extends BaseItem {
  type: 'video';
  src: string;
  poster: string;
  hasAudio: boolean;
}

export interface AudioItem extends BaseItem {
  type: 'audio';
  src: string;
  label: string;
  duration: number;
  color?: string;
}

export type MediaItem = PhotoItem | VideoItem | AudioItem;

/** A media item that has had a position assigned (by Cards.tsx at runtime). */
export type WithPosition<T extends MediaItem> = T & { position: MediaPosition };

export const mediaItems: readonly MediaItem[] = [
`;

const body = items
  .map(
    (it) =>
      `  {\n` +
      `    id: ${JSON.stringify(it.id)},\n` +
      `    type: 'photo',\n` +
      `    src: ${JSON.stringify(it.src)},\n` +
      `    width: ${it.width},\n` +
      `    height: ${it.height},\n` +
      `    caption: ${JSON.stringify(it.caption)},\n` +
      `    alt: ${JSON.stringify(it.alt)},\n` +
      `  },\n`,
  )
  .join('');

const footer = `] as const;\n`;

writeFileSync(OUT_FILE, header + body + footer);
console.log(`Wrote ${items.length} entries to ${OUT_FILE}`);
